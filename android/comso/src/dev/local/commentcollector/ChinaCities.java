    /** Accepts 2-, 4- or 6-digit codes; returns "" when unknown. */
    static String name(String code) {
        if (code == null) return "";
        code = code.trim();
        if (!code.matches("[0-9]{2,12}")) return "";
        if (code.length() >= 4) { String city = C.get(code.substring(0, 4)); if (city != null) return city; }
        String province = P.get(code.substring(0, 2));
        return province == null ? "" : province;
    }
